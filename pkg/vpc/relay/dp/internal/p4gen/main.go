// Command p4gen makes the Go IDs and entry types of the relay pipeline from
// relay.p4info.txtpb and the drop reasons and the PspSa instance from relay.p4.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"hash/fnv"
	"log/slog"
	"os"
	"regexp"
	"sort"
	"strconv"
	"strings"

	p4config "github.com/p4lang/p4runtime/go/p4/config/v1"
	"google.golang.org/protobuf/encoding/prototext"
)

// pspSaType is the P4Runtime extern type ID of PspSa, the first ID for the
// externs of other architectures.
const pspSaType = 0x81

func main() {
	infoPath := flag.String("p4info", "relay.p4info.txtpb", "P4Info text file from p4test")
	srcPath := flag.String("p4", "relay.p4", "P4 source")
	out := flag.String("out", "relay.gen.go", "output Go file")
	pkg := flag.String("package", "dp", "Go package name")
	flag.Parse()
	if err := run(*infoPath, *srcPath, *out, *pkg); err != nil {
		slog.Error("Failed to make the Go code of the P4 program", "error", err)
		os.Exit(1)
	}
}

func run(infoPath, srcPath, out, pkg string) error {
	b, err := os.ReadFile(infoPath)
	if err != nil {
		return err
	}
	info := &p4config.P4Info{}
	if err := prototext.Unmarshal(b, info); err != nil {
		return fmt.Errorf("failed to parse %s: %w", infoPath, err)
	}
	src, err := os.ReadFile(srcPath)
	if err != nil {
		return err
	}
	g := &gen{info: info, src: string(src), infoName: infoPath, srcName: srcPath}
	code, err := g.render(pkg)
	if err != nil {
		return err
	}
	formatted, err := format.Source(code)
	if err != nil {
		return fmt.Errorf("failed to format the output: %w\n%s", err, code)
	}
	return os.WriteFile(out, formatted, 0o644)
}

type gen struct {
	info              *p4config.P4Info
	src               string
	infoName, srcName string
	b                 bytes.Buffer
}

func (g *gen) p(format string, args ...any) { fmt.Fprintf(&g.b, format+"\n", args...) }

var initialisms = map[string]string{"vpc": "VPC", "vni": "VNI", "mtu": "MTU", "spi": "SPI", "id": "ID"}

// camel returns the Go name of the last part of a P4 name.
func camel(name string) string {
	if i := strings.LastIndexByte(name, '.'); i >= 0 {
		name = name[i+1:]
	}
	var s strings.Builder
	for _, part := range strings.Split(name, "_") {
		if part == "" {
			continue
		}
		if v, ok := initialisms[part]; ok {
			s.WriteString(v)
			continue
		}
		s.WriteString(strings.ToUpper(part[:1]) + part[1:])
	}
	return s.String()
}

// field is a match field, an action parameter or a packet metadata field.
type field struct {
	id       uint32
	name     string // Go name.
	p4Name   string
	bits     int32
	typ      string // Go type.
	lpm      bool
	encode   string // Format with the Go value; gives []byte.
	decode   string // Format with the []byte; gives (uint64 or the type, error).
	viaUint  bool   // decode gives a uint64 that needs a conversion.
	typeName string
}

// desc gives the P4 name and the width or the type of f.
func (f field) desc() string {
	if f.typeName != "" {
		return f.p4Name + ", " + f.typeName
	}
	return fmt.Sprintf("%s, %d bits", f.p4Name, f.bits)
}

func (g *gen) field(id uint32, name string, bits int32, typeName string, lpm bool) (field, error) {
	f := field{id: id, name: camel(name), p4Name: name, bits: bits, lpm: lpm, typeName: typeName}
	if typeName != "" {
		nt := g.info.GetTypeInfo().GetNewTypes()[typeName]
		if nt.GetTranslatedType().GetSdnString() == nil {
			return f, fmt.Errorf("field %s: type %s is not translated to a string", name, typeName)
		}
		f.typ, f.encode, f.decode = "string", "[]byte(%s)", "decodeString(%s)"
		return f, nil
	}
	switch {
	case lpm && bits == 128:
		f.typ = "netip.Prefix"
	case bits == 1:
		f.typ, f.encode, f.decode = "bool", "encodeBool(%s)", "decodeBool(%s)"
	case bits == 144:
		f.typ, f.encode, f.decode = "netip.AddrPort", "encodeAddrPort(%s)", "decodeAddrPort(%s)"
	case bits > 0 && bits <= 64:
		f.typ = "uint64"
		for _, w := range []int32{8, 16, 32} {
			if bits <= w {
				f.typ = "uint" + strconv.Itoa(int(w))
				break
			}
		}
		f.encode = "encodeUint(uint64(%s), " + strconv.Itoa(int(bits)) + ")"
		f.decode = "decodeUint(%s, " + strconv.Itoa(int(bits)) + ")"
		f.viaUint = true
	default:
		return f, fmt.Errorf("field %s: no Go type for %d bits", name, bits)
	}
	return f, nil
}

// assign writes the code that decodes b into dst, with errors that name what.
func (g *gen) assign(f field, dst, b, what, zero string) {
	if f.lpm {
		return
	}
	g.p("v, err := %s", fmt.Sprintf(f.decode, b))
	g.p("if err != nil { return %s, fmt.Errorf(\"%s: %%w\", err) }", zero, what)
	if f.viaUint {
		g.p("%s = %s(v)", dst, f.typ)
	} else {
		g.p("%s = v", dst)
	}
}

func (g *gen) render(pkg string) ([]byte, error) {
	info := g.info
	g.p("// SPDX-License-Identifier: AGPL-3.0-only")
	g.p("")
	g.p("// Code generated by p4gen from %s and %s. DO NOT EDIT.", g.infoName, g.srcName)
	g.p("")
	g.p("package %s", pkg)
	g.p("")
	g.p("import (")
	g.p("\"fmt\"")
	g.p("\"net/netip\"")
	g.p("")
	g.p("p4 \"github.com/p4lang/p4runtime/go/p4/v1\"")
	g.p(")")
	g.p("")

	actionName := map[uint32]string{}
	g.p("// Table IDs.")
	g.p("const (")
	for _, t := range info.GetTables() {
		g.p("Table%s uint32 = %d // %s", camel(t.GetPreamble().GetName()), t.GetPreamble().GetId(), t.GetPreamble().GetName())
	}
	g.p(")")
	g.p("")
	g.p("// Action IDs.")
	g.p("const (")
	for _, a := range info.GetActions() {
		n := camel(a.GetPreamble().GetName())
		actionName[a.GetPreamble().GetId()] = n
		g.p("Action%s uint32 = %d // %s", n, a.GetPreamble().GetId(), a.GetPreamble().GetName())
	}
	g.p(")")
	g.p("")
	g.p("// Counter IDs.")
	g.p("const (")
	for _, c := range info.GetCounters() {
		g.p("Counter%s uint32 = %d // %s", strings.TrimSuffix(camel(c.GetPreamble().GetName()), "Counter"), c.GetPreamble().GetId(), c.GetPreamble().GetName())
	}
	g.p(")")
	g.p("")
	g.p("// Meter IDs.")
	g.p("const (")
	for _, m := range info.GetMeters() {
		g.p("Meter%s uint32 = %d // %s", strings.TrimSuffix(camel(m.GetPreamble().GetName()), "Meter"), m.GetPreamble().GetId(), m.GetPreamble().GetName())
	}
	g.p(")")
	g.p("")
	g.p("// Controller packet metadata IDs.")
	g.p("const (")
	for _, c := range info.GetControllerPacketMetadata() {
		g.p("%sID uint32 = %d", camel(c.GetPreamble().GetName()), c.GetPreamble().GetId())
	}
	g.p(")")
	g.p("")

	inst, err := g.pspSaInstance()
	if err != nil {
		return nil, err
	}
	g.p("// The PspSa extern: its P4Runtime type ID, and the ID and name of its one instance.")
	g.p("const (")
	g.p("ExternPspSa uint32 = %#x", pspSaType)
	g.p("Extern%s uint32 = %#x", camel(inst), externID(inst))
	g.p("extern%sName = %q", camel(inst), inst)
	g.p(")")
	g.p("")

	reasons, err := g.reasons()
	if err != nil {
		return nil, err
	}
	g.p("// Drop reasons of %s: the index in the drops counter.", g.srcName)
	g.p("const (")
	for _, r := range reasons {
		g.p("Reason%s uint8 = %d", r.name, r.value)
	}
	g.p(")")
	g.p("")

	g.p("// counterSizes has the size of each counter.")
	g.p("var counterSizes = map[uint32]int64{")
	for _, c := range info.GetCounters() {
		g.p("%d: %d,", c.GetPreamble().GetId(), c.GetSize())
	}
	g.p("}")
	g.p("")
	g.p("// meterSizes has the size of each meter, and meterPackets the meters that count packets.")
	g.p("var meterSizes = map[uint32]int64{")
	for _, m := range info.GetMeters() {
		g.p("%d: %d,", m.GetPreamble().GetId(), m.GetSize())
	}
	g.p("}")
	g.p("var meterPackets = map[uint32]bool{")
	for _, m := range info.GetMeters() {
		g.p("%d: %t,", m.GetPreamble().GetId(), m.GetSpec().GetUnit() == p4config.MeterSpec_PACKETS)
	}
	g.p("}")
	g.p("")

	if err := g.actions(); err != nil {
		return nil, err
	}
	if err := g.tables(actionName); err != nil {
		return nil, err
	}
	if err := g.packetMetadata(); err != nil {
		return nil, err
	}
	return g.b.Bytes(), nil
}

// actionType returns the Go type name of an action.
func actionType(name string) string {
	n := camel(name)
	if strings.HasSuffix(n, "Action") {
		return n
	}
	return n + "Action"
}

func (g *gen) actions() error {
	g.p("// Action is the action of a table entry: one of the action types of this file.")
	g.p("type Action interface {")
	g.p("ActionID() uint32")
	g.p("params() []*p4.Action_Param")
	g.p("}")
	g.p("")
	for _, a := range g.info.GetActions() {
		name, alias := a.GetPreamble().GetName(), a.GetPreamble().GetAlias()
		typ := actionType(name)
		var fields []field
		for _, prm := range a.GetParams() {
			f, err := g.field(prm.GetId(), prm.GetName(), prm.GetBitwidth(), prm.GetTypeName().GetName(), false)
			if err != nil {
				return fmt.Errorf("action %s: %w", name, err)
			}
			fields = append(fields, f)
		}
		g.p("// %s is the %s action.", typ, name)
		if len(fields) == 0 {
			g.p("type %s struct{}", typ)
		} else {
			g.p("type %s struct {", typ)
			for _, f := range fields {
				g.p("%s %s // %s", f.name, f.typ, f.desc())
			}
			g.p("}")
		}
		g.p("")
		g.p("// ActionID returns the ID of the %s action.", name)
		g.p("func (%s) ActionID() uint32 { return Action%s }", typ, camel(name))
		g.p("")
		if len(fields) == 0 {
			g.p("func (%s) params() []*p4.Action_Param { return nil }", typ)
		} else {
			g.p("func (a %s) params() []*p4.Action_Param {", typ)
			g.p("return []*p4.Action_Param{")
			for _, f := range fields {
				g.p("{ParamId: %d, Value: %s},", f.id, fmt.Sprintf(f.encode, "a."+f.name))
			}
			g.p("}")
			g.p("}")
		}
		g.p("")
		g.p("func decode%s(ps []*p4.Action_Param) (%s, error) {", typ, typ)
		g.p("var a %s", typ)
		g.p("var seen uint64")
		g.p("for _, prm := range ps {")
		g.p("id := prm.GetParamId()")
		g.p("if id == 0 || id > 63 || seen&(1<<id) != 0 { return a, fmt.Errorf(\"%s: parameter %%d is not valid or repeated\", id) }", alias)
		g.p("seen |= 1 << id")
		g.p("switch id {")
		var all uint64
		for _, f := range fields {
			all |= 1 << f.id
			g.p("case %d:", f.id)
			g.assign(f, "a."+f.name, "prm.GetValue()", alias+" "+f.p4Name, "a")
		}
		g.p("default:")
		g.p("return a, fmt.Errorf(\"%s: unknown parameter %%d\", id)", alias)
		g.p("}")
		g.p("}")
		g.p("if seen != %#x { return a, fmt.Errorf(\"%s: a parameter is missing\") }", all, alias)
		g.p("return a, nil")
		g.p("}")
		g.p("")
	}
	g.p("// decodeAction returns the action of a.")
	g.p("func decodeAction(a *p4.Action) (Action, error) {")
	g.p("switch a.GetActionId() {")
	for _, a := range g.info.GetActions() {
		g.p("case Action%s:", camel(a.GetPreamble().GetName()))
		g.p("return decode%s(a.GetParams())", actionType(a.GetPreamble().GetName()))
	}
	g.p("}")
	g.p("return nil, fmt.Errorf(\"unknown action %%d\", a.GetActionId())")
	g.p("}")
	g.p("")
	return nil
}

func (g *gen) tables(actionName map[uint32]string) error {
	g.p("// tableAction returns the P4Runtime action of a, or nil for no action (DELETE).")
	g.p("func tableAction(a Action) *p4.TableAction {")
	g.p("if a == nil { return nil }")
	g.p("return &p4.TableAction{Type: &p4.TableAction_Action{Action: &p4.Action{ActionId: a.ActionID(), Params: a.params()}}}")
	g.p("}")
	g.p("")
	g.p("// defaultActions has the initial default action of each table.")
	g.p("var defaultActions = map[uint32]*p4.Action{")
	for _, t := range g.info.GetTables() {
		d := t.GetInitialDefaultAction()
		if d == nil {
			continue
		}
		var ps []string
		for _, a := range d.GetArguments() {
			ps = append(ps, fmt.Sprintf("{ParamId: %d, Value: %#v}", a.GetParamId(), a.GetValue()))
		}
		g.p("Table%s: {ActionId: %d, Params: []*p4.Action_Param{%s}},", camel(t.GetPreamble().GetName()), d.GetActionId(), strings.Join(ps, ", "))
	}
	g.p("}")
	g.p("")
	for _, t := range g.info.GetTables() {
		name, alias := t.GetPreamble().GetName(), t.GetPreamble().GetAlias()
		typ := camel(name) + "Key"
		var fields []field
		for _, m := range t.GetMatchFields() {
			lpm := m.GetMatchType() == p4config.MatchField_LPM
			if !lpm && m.GetMatchType() != p4config.MatchField_EXACT {
				return fmt.Errorf("table %s: match type %v is not supported", name, m.GetMatchType())
			}
			f, err := g.field(m.GetId(), m.GetName(), m.GetBitwidth(), m.GetTypeName().GetName(), lpm)
			if err != nil {
				return fmt.Errorf("table %s: %w", name, err)
			}
			if lpm && f.typ != "netip.Prefix" {
				return fmt.Errorf("table %s: LPM field %s is not 128 bits", name, m.GetName())
			}
			fields = append(fields, f)
		}
		g.p("// %s is the match key of the %s table.", typ, name)
		g.p("type %s struct {", typ)
		for _, f := range fields {
			g.p("%s %s // %s", f.name, f.typ, f.p4Name)
		}
		g.p("}")
		g.p("")
		g.p("// Entry returns the %s entry of k with action a.", name)
		g.p("func (k %s) Entry(a Action) *p4.TableEntry {", typ)
		g.p("return &p4.TableEntry{TableId: Table%s, Match: k.match(), Action: tableAction(a)}", camel(name))
		g.p("}")
		g.p("")
		g.p("func (k %s) match() []*p4.FieldMatch {", typ)
		g.p("ms := make([]*p4.FieldMatch, 0, %d)", len(fields))
		for _, f := range fields {
			if f.lpm {
				g.p("if l := encodeLPM(k.%s); l != nil {", f.name)
				g.p("ms = append(ms, &p4.FieldMatch{FieldId: %d, FieldMatchType: &p4.FieldMatch_Lpm{Lpm: l}})", f.id)
				g.p("}")
				continue
			}
			g.p("ms = append(ms, &p4.FieldMatch{FieldId: %d, FieldMatchType: &p4.FieldMatch_Exact_{Exact: &p4.FieldMatch_Exact{Value: %s}}})", f.id, fmt.Sprintf(f.encode, "k."+f.name))
		}
		g.p("return ms")
		g.p("}")
		g.p("")
		g.p("func decode%s(ms []*p4.FieldMatch) (%s, error) {", typ, typ)
		g.p("var k %s", typ)
		var exact uint64
		for _, f := range fields {
			if f.lpm {
				g.p("k.%s = anyPrefix", f.name)
			} else {
				exact |= 1 << f.id
			}
		}
		g.p("var seen uint64")
		g.p("for _, m := range ms {")
		g.p("id := m.GetFieldId()")
		g.p("if id == 0 || id > 63 || seen&(1<<id) != 0 { return k, fmt.Errorf(\"%s: match field %%d is not valid or repeated\", id) }", alias)
		g.p("seen |= 1 << id")
		g.p("switch id {")
		for _, f := range fields {
			g.p("case %d:", f.id)
			if f.lpm {
				g.p("l := m.GetLpm()")
				g.p("if l == nil { return k, fmt.Errorf(\"%s %s: not an LPM match\") }", alias, f.p4Name)
				g.p("p, err := decodeLPM(l)")
				g.p("if err != nil { return k, fmt.Errorf(\"%s %s: %%w\", err) }", alias, f.p4Name)
				g.p("k.%s = p", f.name)
				continue
			}
			g.p("e := m.GetExact()")
			g.p("if e == nil { return k, fmt.Errorf(\"%s %s: not an exact match\") }", alias, f.p4Name)
			g.assign(f, "k."+f.name, "e.GetValue()", alias+" "+f.p4Name, "k")
		}
		g.p("default:")
		g.p("return k, fmt.Errorf(\"%s: unknown match field %%d\", id)", alias)
		g.p("}")
		g.p("}")
		g.p("if seen&%#x != %#x { return k, fmt.Errorf(\"%s: an exact match field is missing\") }", exact, exact, alias)
		g.p("return k, nil")
		g.p("}")
		g.p("")
		var allowed []string
		for _, r := range t.GetActionRefs() {
			if r.GetScope() == p4config.ActionRef_DEFAULT_ONLY {
				continue
			}
			allowed = append(allowed, "Action"+actionName[r.GetId()])
		}
		sort.Strings(allowed)
		g.p("// %sAllows reports whether an entry of %s can have the action id.", lowerFirst(camel(name)), name)
		g.p("func %sAllows(id uint32) bool {", lowerFirst(camel(name)))
		g.p("switch id {")
		g.p("case %s:", strings.Join(allowed, ", "))
		g.p("return true")
		g.p("}")
		g.p("return false")
		g.p("}")
		g.p("")
	}
	return nil
}

func lowerFirst(s string) string { return strings.ToLower(s[:1]) + s[1:] }

func (g *gen) packetMetadata() error {
	for _, c := range g.info.GetControllerPacketMetadata() {
		name := c.GetPreamble().GetName()
		typ := camel(name) + "Meta"
		var fields []field
		for _, m := range c.GetMetadata() {
			f, err := g.field(m.GetId(), m.GetName(), m.GetBitwidth(), m.GetTypeName().GetName(), false)
			if err != nil {
				return fmt.Errorf("controller header %s: %w", name, err)
			}
			fields = append(fields, f)
		}
		g.p("// %s is the %s controller header.", typ, name)
		g.p("type %s struct {", typ)
		for _, f := range fields {
			g.p("%s %s // %s", f.name, f.typ, f.desc())
		}
		g.p("}")
		g.p("")
		g.p("// Metadata returns the P4Runtime metadata of m.")
		g.p("func (m %s) Metadata() []*p4.PacketMetadata {", typ)
		g.p("return []*p4.PacketMetadata{")
		for _, f := range fields {
			g.p("{MetadataId: %d, Value: %s},", f.id, fmt.Sprintf(f.encode, "m."+f.name))
		}
		g.p("}")
		g.p("}")
		g.p("")
		g.p("// Decode%s returns the %s header of md. A field that is not in md is zero.", typ, name)
		g.p("func Decode%s(md []*p4.PacketMetadata) (%s, error) {", typ, typ)
		g.p("var m %s", typ)
		g.p("for _, x := range md {")
		g.p("switch x.GetMetadataId() {")
		for _, f := range fields {
			g.p("case %d:", f.id)
			g.assign(f, "m."+f.name, "x.GetValue()", name+" "+f.p4Name, "m")
		}
		g.p("default:")
		g.p("return m, fmt.Errorf(\"%s: unknown metadata %%d\", x.GetMetadataId())", name)
		g.p("}")
		g.p("}")
		g.p("return m, nil")
		g.p("}")
		g.p("")
	}
	return nil
}

type reason struct {
	name  string
	value int
}

var reasonRE = regexp.MustCompile(`(?m)^const bit<8> R_([A-Z0-9_]+) = (\d+);`)

// reasons returns the R_ constants of the P4 source.
func (g *gen) reasons() ([]reason, error) {
	var rs []reason
	for _, m := range reasonRE.FindAllStringSubmatch(g.src, -1) {
		v, err := strconv.Atoi(m[2])
		if err != nil {
			return nil, err
		}
		rs = append(rs, reason{name: camel(strings.ToLower(m[1])), value: v})
	}
	if len(rs) == 0 {
		return nil, fmt.Errorf("%s has no R_ constants", g.srcName)
	}
	return rs, nil
}

var pspSaRE = regexp.MustCompile(`(?m)^\s*PspSa\([^)]*\)\s+(\w+);`)

// pspSaInstance returns the full name of the one PspSa instance, with the
// control name of the tables as its prefix.
func (g *gen) pspSaInstance() (string, error) {
	ms := pspSaRE.FindAllStringSubmatch(g.src, -1)
	if len(ms) != 1 {
		return "", fmt.Errorf("%s must have one PspSa instance, found %d", g.srcName, len(ms))
	}
	tables := g.info.GetTables()
	if len(tables) == 0 {
		return "", fmt.Errorf("P4Info has no tables")
	}
	ctl, _, ok := strings.Cut(tables[0].GetPreamble().GetName(), ".")
	if !ok {
		return "", fmt.Errorf("table %s has no control name", tables[0].GetPreamble().GetName())
	}
	return ctl + "." + ms[0][1], nil
}

// externID gives an instance of PspSa an ID: the type in the top 8 bits and
// a hash of the name below, as p4c does for its own objects.
func externID(name string) uint32 {
	h := fnv.New32a()
	h.Write([]byte(name))
	return pspSaType<<24 | h.Sum32()&0xffffff
}
